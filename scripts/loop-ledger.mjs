#!/usr/bin/env node
// The loop ledger: every pull request, every commit's "TestSprite V3" verdict as GitHub recorded it, and how the PR
// ended. Written to docs/LOOP.md from the GitHub API (gh CLI), so it can be regenerated and checked, not hand-edited.
// Usage: node scripts/loop-ledger.mjs [owner/repo]
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const repo = process.argv[2] ?? "PugarHuda/tera";
const gh = (...args) => JSON.parse(execFileSync("gh", ["api", "--paginate", ...args], { encoding: "utf8", maxBuffer: 64 << 20 }));
const CONTEXT = "TestSprite V3";

const prs = gh(`repos/${repo}/pulls?state=all&per_page=100`).sort((a, b) => a.number - b.number);
const rows = [];
const tally = { prs: prs.length, checked: 0, red: 0, redToGreen: 0, credits: 0 };
for (const pr of prs) {
  const commits = gh(`repos/${repo}/pulls/${pr.number}/commits?per_page=100`);
  const verdicts = [];
  for (const c of commits) {
    // Older runs reported a commit status, newer ones a check run of the same name.
    const s = gh(`repos/${repo}/commits/${c.sha}/status`).statuses.find((x) => x.context === CONTEXT);
    if (s) verdicts.push({ sha: c.sha.slice(0, 7), state: s.state, description: s.description ?? "" });
    else {
      const run = gh(`repos/${repo}/commits/${c.sha}/check-runs`).check_runs?.find((x) => x.name === CONTEXT);
      if (run) verdicts.push({ sha: c.sha.slice(0, 7), state: run.conclusion === "success" ? "success" : run.conclusion ? "failure" : "pending", description: run.output?.title ?? "" });
    }
  }
  if (verdicts.length) tally.checked++;
  const red = verdicts.filter((v) => v.state === "failure" || v.state === "error");
  // A credit outage is not a test verdict: the check never ran the suite.
  const outage = red.filter((v) => /credit|billing/i.test(v.description));
  const realRed = red.filter((v) => !outage.includes(v));
  if (realRed.length) tally.red++;
  if (outage.length) tally.credits++;
  // Fixed in the PR: a passing run after its last real failure.
  const fixed = realRed.length > 0 && verdicts.slice(verdicts.indexOf(realRed.at(-1)) + 1).some((v) => v.state === "success");
  if (fixed) tally.redToGreen++;
  const end = pr.merged_at ? `merged ${pr.merged_at.slice(0, 10)}` : pr.state === "open" ? "open" : "closed, not merged";
  const trail = verdicts.map((v) => `${v.state === "success" ? "✅" : v.state === "pending" ? "⏳" : "❌"} ${v.sha} ${v.description}`).join("<br>");
  const note = outage.length && !realRed.length ? "credits ran out: the suite did not run (not a test result)" : realRed.length ? (fixed ? "red → green" : "red") : "";
  rows.push(`| [#${pr.number}](https://github.com/${repo}/pull/${pr.number}) | ${pr.title.replace(/\|/g, "\\|")} | ${trail || "no TestSprite check"} | ${end} | ${note} |`);
}

const md = `# Loop ledger

Every pull request and the \`${CONTEXT}\` verdict GitHub recorded for each of its commits, generated by
[\`scripts/loop-ledger.mjs\`](../scripts/loop-ledger.mjs) from the GitHub API on ${new Date().toISOString().slice(0, 10)}.

- ${tally.prs} pull requests, ${tally.checked} with a TestSprite check
- ${tally.red} went red on a real test result; ${tally.redToGreen} of them were fixed in the same PR (red → green)
- ${tally.credits} were blocked because the workspace ran out of TestSprite credits. The check then reports
  "Not enough credits" without running a test, so those PRs were merged by the repository admin after every other
  check (unit, Stripe parity, Playwright journeys, Schemathesis, Arazzo, Lighthouse) passed. They are listed, not hidden.

| PR | Title | ${CONTEXT} per commit | Outcome | Note |
|---|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync("docs/LOOP.md", md);
console.log(`docs/LOOP.md: ${tally.prs} PRs, ${tally.checked} checked, ${tally.red} red, ${tally.redToGreen} red→green, ${tally.credits} credit outages`);
